#!/usr/bin/env bash
# Run on the home server. Writes Secrets.swift from the receiver's token, copies the
# watch project to the Mac, and checks that it compiles for the simulator (no signing,
# so SSH is fine). With --install, also asks the Mac's GUI build agent to build and
# install on the watch (watch must be awake, unlocked, and near the iPhone).
set -euo pipefail
cd "$(dirname "$0")"
TOKEN="$(cat ~/.config/watch-dictate/token)"
CF_ID="$(grep -oP '^CF_ACCESS_CLIENT_ID=\K.+' ~/.config/watch-dictate/cf-access.env)"
CF_SECRET="$(grep -oP '^CF_ACCESS_CLIENT_SECRET=\K.+' ~/.config/watch-dictate/cf-access.env)"
umask 077
cat > Shared/Secrets.swift <<SWIFT
// Generated by sync-to-mac.sh - do not commit.
enum Secrets {
    static let token = "$TOKEN"
    static let accessClientId = "$CF_ID"
    static let accessClientSecret = "$CF_SECRET"
}
SWIFT
ssh your-mac 'mkdir -p ~/projects/watch-dictate/watch'
rsync -a --delete --exclude '*.xcodeproj' --exclude '.DS_Store' ./ your-mac:projects/watch-dictate/watch/
ssh your-mac 'cd ~/projects/watch-dictate/watch && X="$HOME/.local/xcodegen/bin/xcodegen"; [ -x "$X" ] || X=xcodegen; "$X" generate -q &&
  if xcodebuild -project WatchDictate.xcodeproj -scheme WatchDictate -destination "generic/platform=watchOS Simulator" \
       -derivedDataPath /tmp/wd-sim-dd CODE_SIGNING_ALLOWED=NO build > /tmp/wd-sim-build.log 2>&1;
  then echo "simulator build OK"; else grep -E "error:" /tmp/wd-sim-build.log | head -30; echo "simulator build FAILED"; exit 1; fi'
if [[ "${1:-}" == "--install" ]]; then
  ssh your-mac 'echo watchdictate > ~/.ios-build-trigger'
  echo 'Triggered the GUI build agent; follow ~/Library/Logs/ios-build-agent.log on the Mac.'
fi
